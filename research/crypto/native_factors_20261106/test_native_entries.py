def market_fixture(market):
    future = market == "futures"
    return dict(id="BTCUSDT", symbol=pair(market), base="BTC", quote="USDT", settle="USDT" if future else None,
                baseId="BTC", quoteId="USDT", settleId="USDT" if future else None,
                type="swap" if future else "spot", spot=not future, margin=False, swap=future,
                future=False, option=False, linear=future, inverse=False, contract=future,
                contractSize=1 if future else None, active=True,
                precision={"amount": .01, "price": .01},
                limits={"amount": {"min": .01, "max": 10000}, "price": {"min": .01, "max": 1000000},
                        "cost": {"min": 5, "max": None}},
                maker=.0013, taker=.0013, info={"orderTypes": ["LIMIT", "MARKET"]})


class NativeEntryTests(unittest.TestCase):
    def setUp(self):
        self.stack = ExitStack()
        self.root = Path(self.stack.enter_context(tempfile.TemporaryDirectory(prefix="native-entry-test-")))
        for name in ("socket.socket.connect", "socket.socket.connect_ex", "socket.create_connection", "socket.getaddrinfo"):
            self.stack.enter_context(patch(name, side_effect=AssertionError("network forbidden")))
        init_db("sqlite:///" + str(self.root / "native.sqlite")); Trade.use_db = True
        self.opened = []

    def tearDown(self):
        for obj in reversed(self.opened): obj.close()
        engine = Trade.session.get_bind()
        Trade.session.remove(); _CustomData.session.remove(); engine.dispose()
        self.stack.close()

    def harness(self, market="spot", response="NEW", *, lose_reply=False):
        life = Lifecycle(self.root / market, "synthetic-entry", market, create=True)
        self.opened.append(life)
        gate = NativeEntryGate(self.root / (market + "-receipts"), life, create=True)
        self.opened.append(gate)
        # Client ID is known from the immutable account/request identity, not generated by the fake server.
        from rd1 import digest
        client = "rd1-" + digest({"account": life.s["identity"], "request": "r1"})[:28]
        payload = {"symbol": "BTCUSDT", "orderId": 100, "clientOrderId": client,
                   "transactTime": int(T.timestamp()*1000), "updateTime": int(T.timestamp()*1000),
                   "price": "10.00", "origQty": "5.00", "executedQty": "0.00",
                   "cummulativeQuoteQty": "0.00", "cumQuote": "0.00", "avgPrice": "0.00",
                   "status": response, "timeInForce": "GTC", "type": "LIMIT", "side": "BUY"}
        tape = LocalBinanceTape([market_fixture(market)], [ccxt.RequestTimeout("synthetic response lost") if lose_reply else (payload, T)])
        ex = ReplayEntryExchange(tape, gate, market); self.opened.append(ex)
        # Rates, fee estimate and wallet effects remain explicit synthetic boundaries.
        ex.get_fee = Mock(return_value=.0013)
        bot = SimpleNamespace(exchange=ex, config={"stake_currency": "USDT", "timeframe": "5m"},
            strategy=SimpleNamespace(order_time_in_force={"entry":"GTC"}, order_types={"entry":"limit"},
                confirm_trade_entry=lambda **kw: True, get_strategy_name=lambda: "synthetic-RD1-entry", stoploss=-.05),
            get_valid_enter_price_and_stake=Mock(return_value=(10.0,50.0,1.0)),
            trading_mode=TradingMode(market), wallets=SimpleNamespace(update=Mock()), _notify_enter=Mock())
        bot.execute_entry = MethodType(FreqtradeBot.execute_entry, bot)
        evidence = AccountEvidence("synthetic-entry", market, "synthetic-full-account", "synthetic", snapshot(market),
            True, True, True, {}, {}, (), {})
        return life, gate, ex, bot, evidence, entry(market)

    def execute(self, ex, bot, e, proposal, request="r1"):
        with ex.for_entry(request, e, proposal, T):
            return bot.execute_entry(proposal.pair, 50)

    def test_real_native_and_ccxt_builders_persist_initial_order_and_client_identity(self):
        for market in ("spot", "futures"):
            with self.subTest(market=market):
                life, gate, ex, bot, e, p = self.harness(market)
                self.assertTrue(self.execute(ex, bot, e, p))
                row = Trade.get_trades_proxy()[0]
                binding = gate.bind_native("r1")
                self.assertEqual(binding["trade_id"], row.id)
                self.assertEqual(row.orders[0].order_id, "100")
                self.assertEqual(row.amount, 0)  # open unfilled order is not inventory
                request = ex._api.requests[0]
                self.assertEqual(request["params"]["newClientOrderId"], life.s["requests"]["r1"]["lifecycle"]["client_order_id"])
                self.assertEqual(request["params"]["quantity"], "5")
                self.assertEqual(request["params"]["price"], "10")
                self.assertEqual(request["api"], ["private"] if market == "spot" else ["fapiPrivate"])
                self.assertNotIn("clientOrderId", row.orders[0].to_ccxt_object())
                self.assertEqual(gate.s["requests"]["r1"]["venue_payload"]["clientOrderId"], request["params"]["newClientOrderId"])
                self.assertEqual(life.s["requests"]["r1"]["lifecycle"]["state"], "SUBMISSION_UNKNOWN")
                # Separate isolated native DB for the next market, no real DB touched.
                Trade.session.delete(row); Trade.commit()

    def test_lost_reply_restart_cannot_submit_twice(self):
        life, gate, ex, bot, e, p = self.harness(lose_reply=True)
        from freqtrade.exceptions import TemporaryError
        with self.assertRaises(TemporaryError): self.execute(ex, bot, e, p)
        self.assertEqual(len(ex._api.requests), 1)
        self.assertEqual(Trade.get_trades_proxy(), [])
        gate.close(); life.close()
        restarted = Lifecycle(self.root / "spot", "synthetic-entry", "spot"); self.opened.append(restarted)
        gate2 = NativeEntryGate(self.root / "spot-receipts", restarted); self.opened.append(gate2)
        ex.gate = gate2
        with self.assertRaisesRegex(StateError, "already consumed"):
            self.execute(ex, bot, e, p)
        with self.assertRaisesRegex(RiskError, "outstanding_reservation_same_pair"):
            self.execute(ex, bot, e, p, request="r2")
        self.assertEqual(len(ex._api.requests), 1)
        self.assertEqual(gate2.s["requests"]["r1"]["state"], "SUBMISSION_UNKNOWN")

    def test_native_commit_failure_preserves_response_and_pending_risk(self):
        life, gate, ex, bot, e, p = self.harness()
        with patch.object(Trade, "commit", side_effect=RuntimeError("synthetic DB write failed")):
            with self.assertRaises(RuntimeError): self.execute(ex, bot, e, p)
        Trade.session.rollback()
        self.assertEqual(Trade.get_trades_proxy(), [])
        self.assertEqual(gate.s["requests"]["r1"]["state"], "RESPONSE_CAPTURED")
        with self.assertRaisesRegex(RiskError, "missing or ambiguous"): gate.bind_native("r1")
        with self.assertRaisesRegex(StateError, "already consumed"): self.execute(ex, bot, e, p)
        self.assertEqual(len(ex._api.requests), 1)

    def test_precision_difference_rejected_before_reservation_or_request(self):
        life, gate, ex, bot, e, p = self.harness()
        p = replace(p, quantity=D("5.005"))
        bot.get_valid_enter_price_and_stake.return_value = (10.0,50.05,1.0)
        with self.assertRaisesRegex(RiskError, "precision changes"): self.execute(ex, bot, e, p)
        self.assertEqual(life.s["requests"], {})
        self.assertEqual(ex._api.requests, [])

    def test_unknown_context_and_changed_native_order_never_reach_transport(self):
        life, gate, ex, bot, e, p = self.harness()
        with self.assertRaisesRegex(RiskError, "No explicit"): bot.execute_entry(p.pair,50)
        bot.get_valid_enter_price_and_stake.return_value = (10.,60.,1.)
        with self.assertRaisesRegex(RiskError, "differs from"): self.execute(ex, bot, e, p)
        self.assertEqual(ex._api.requests, [])
        self.assertEqual(life.s["requests"], {})

    def test_unmatched_response_identity_is_preserved_but_not_given_to_bot(self):
        life, gate, ex, bot, e, p = self.harness()
        ex._api.responses[0][0]["clientOrderId"] = "wrong-client-id"
        with self.assertRaisesRegex(RiskError, "differs from claimed"): self.execute(ex, bot, e, p)
        self.assertEqual(Trade.get_trades_proxy(), [])
        self.assertEqual(gate.s["requests"]["r1"]["ccxt_payload"]["clientOrderId"], "wrong-client-id")
        with self.assertRaisesRegex(StateError, "already consumed"): self.execute(ex, bot, e, p)
        self.assertEqual(len(ex._api.requests), 1)

    def test_receipt_write_failure_after_claim_never_reaches_transport(self):
        life, gate, ex, bot, e, p = self.harness()
        with patch.object(gate.store, "save", side_effect=OSError("synthetic disk failure")):
            with self.assertRaisesRegex(StateError, "not durably acknowledged"): self.execute(ex, bot, e, p)
        self.assertEqual(ex._api.requests, [])
        self.assertEqual(life.s["requests"]["r1"]["lifecycle"]["state"], "SUBMISSION_UNKNOWN")
        with self.assertRaisesRegex(StateError, "unavailable"): self.execute(ex, bot, e, p)

    def test_zero_rejection_keeps_source_receipt_without_native_trade(self):
        life, gate, ex, bot, e, p = self.harness(response="REJECTED")
        self.assertFalse(self.execute(ex, bot, e, p))
        self.assertEqual(Trade.get_trades_proxy(), [])
        self.assertEqual(gate.s["requests"]["r1"]["ccxt_payload"]["status"], "rejected")
        self.assertEqual(life.s["requests"]["r1"]["lifecycle"]["state"], "SUBMISSION_UNKNOWN")

    def test_stale_account_and_stricter_native_rules_reject_before_claim(self):
        life, gate, ex, bot, e, p = self.harness()
        stale = replace(e, snapshot=replace(e.snapshot, at=T-timedelta(seconds=16)))
        with self.assertRaisesRegex(RiskError, "stale or future"):
            self.execute(ex, bot, stale, p)
        ex._markets[p.pair]["limits"]["cost"]["min"] = 6
        with self.assertRaisesRegex(RiskError, "minimum notional"):
            self.execute(ex, bot, e, p)
        self.assertEqual(life.s["requests"], {})
        self.assertEqual(ex._api.requests, [])

    def test_invalid_response_cannot_bind_even_if_native_row_exists(self):
        life, gate, ex, bot, e, p = self.harness()
        ex._api.responses[0][0]["clientOrderId"] = "wrong"
        with self.assertRaises(RiskError): self.execute(ex, bot, e, p)
        raw = gate.s["requests"]["r1"]["ccxt_payload"]
        trade = Trade(pair=p.pair, stake_currency="USDT", exchange="binance", amount=0,
                      stake_amount=50, open_rate=10, is_open=True, open_date=T,
                      fee_open=.0013, fee_close=.0013, leverage=1, is_short=False, trading_mode=TradingMode.SPOT)
        trade.orders.append(Order.parse_from_ccxt_object(raw, p.pair, "buy"))
        Trade.session.add(trade); Trade.commit()
        with self.assertRaisesRegex(RiskError, "differs from claimed"): gate.bind_native("r1")

    def test_native_commit_ack_loss_preserves_rows_and_prevents_second_attempt(self):
        life, gate, ex, bot, e, p = self.harness()
        original = Trade.commit
        def commit_then_fail():
            original()
            raise RuntimeError("synthetic native commit acknowledgement lost")
        with patch.object(Trade, "commit", side_effect=commit_then_fail):
            with self.assertRaisesRegex(RuntimeError, "acknowledgement lost"):
                self.execute(ex, bot, e, p)
        Trade.session.remove()
        self.assertEqual(len(Trade.get_trades_proxy()), 1)
        self.assertEqual(gate.bind_native("r1")["venue_order_id"], "100")
        # Repeating with the stale flat snapshot is rejected by native inventory,
        # even before the already-consumed attempt check.
        with self.assertRaisesRegex(RiskError, "open order inventories"):
            self.execute(ex, bot, e, p)
        self.assertEqual(len(ex._api.requests), 1)
        self.assertEqual(life.s["requests"]["r1"]["lifecycle"]["state"], "SUBMISSION_UNKNOWN")

    def test_post_claim_receipt_ack_loss_does_not_retry_transport(self):
        life, gate, ex, bot, e, p = self.harness()
        original = gate.store.save
        def fail_after_commit(state):
            original(state)
            if state["requests"].get("r1", {}).get("state") == "RESPONSE_CAPTURED":
                raise OSError("synthetic response receipt commit acknowledgement lost")
        with patch.object(gate.store, "save", side_effect=fail_after_commit):
            with self.assertRaisesRegex(StateError, "not durably acknowledged"):
                self.execute(ex, bot, e, p)
        self.assertEqual(Trade.get_trades_proxy(), [])
        gate.close(); life.close()
        restarted = Lifecycle(self.root/"spot", "synthetic-entry", "spot"); self.opened.append(restarted)
        recovered = NativeEntryGate(self.root/"spot-receipts", restarted); self.opened.append(recovered)
        self.assertEqual(recovered.s["requests"]["r1"]["state"], "RESPONSE_CAPTURED")
        ex.gate = recovered
        with self.assertRaisesRegex(StateError, "already consumed"): self.execute(ex, bot, e, p)
        self.assertEqual(len(ex._api.requests), 1)


