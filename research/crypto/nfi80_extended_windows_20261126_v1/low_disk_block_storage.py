"""Read only native callback rows from audited blocks while keeping disk bounded."""

from collections import OrderedDict
import hashlib
import pickle

import pandas as pd
import pyarrow as pa

from research.crypto.nfi40_frame_cache_native_20261117_v1.frame_storage_v3 import semantic_digest
from research.crypto.nfi80_extended_windows_20261126_v1.low_disk_storage import (
    ReplayStorage as OriginalLifecycle, ReplayStorageError, trim_dates,
)


BLOCK_ROWS = 2048
BLOCK_LRU = 64
DISK_LIMIT = 1024 ** 3
CODEC = pa.Codec("zstd")


class FrameView:
    def __init__(self, owner, key, frame):
        self.owner = owner
        self.key = key
        self.index = frame.index.copy()
        self.template = frame.iloc[:0].copy(deep=True)

    @property
    def iloc(self):
        return self

    def __getitem__(self, rows):
        try:
            if not isinstance(rows, slice) or rows.step not in (None, 1):
                raise ReplayStorageError("Native DataProvider requested a non-contiguous analyzed slice")
            start, stop, _ = rows.indices(len(self.index))
            out = self.owner.read_slice(self.key, start, stop, self.template)
            out.index = self.index[rows]
            return out
        except Exception as error:
            raise ReplayStorageError(f"Unable to reconstruct native slice for {self.key[0]}") from error


class AnalyzedBlocks:
    def __init__(self, owner, root):
        self.owner = owner
        self.root = root
        root.mkdir()
        self.records = {}
        self.disk = OrderedDict()
        self.resident = OrderedDict()
        self.bytes_stored = 0
        self.peak_bytes = 0
        self.rebuilt = 0
        self.disk_reads = 0
        self.evicted = 0
        self.hits = 0

    def __contains__(self, key):
        return key in self.records

    def __setitem__(self, key, value):
        if key in self.records:
            raise ReplayStorageError("Unexpected repeated native analyzed-frame assignment")
        frame, refreshed = value
        self.records[key] = (
            FrameView(self, key, frame), refreshed, self.owner.provider.backtest_time,
            semantic_digest(frame),
        )

    def __getitem__(self, key):
        return self.records[key][:2]

    def _store(self, key, block):
        raw = pickle.dumps(block, protocol=5)
        blob = CODEC.compress(raw, asbytes=True)
        while self.bytes_stored + len(blob) > DISK_LIMIT and self.disk:
            _, (old, stored_size, *_rest) = self.disk.popitem(last=False)
            old.unlink()
            self.bytes_stored -= stored_size
            self.evicted += 1
        if len(blob) > DISK_LIMIT:
            raise ReplayStorageError("A single analyzed block exceeds the study's disk bound")
        token = hashlib.sha256(pickle.dumps(key, protocol=5)).hexdigest()
        path = self.root / f"{token}.pkl"
        with path.open("xb") as output:
            output.write(blob)
        self.disk[key] = (path, len(blob), len(raw), hashlib.sha256(blob).digest(), hashlib.sha256(raw).digest())
        self.bytes_stored += len(blob)
        self.peak_bytes = max(self.peak_bytes, self.bytes_stored)

    def _load(self, key):
        if key in self.resident:
            self.resident.move_to_end(key)
            self.hits += 1
            return self.resident[key]
        path, size, raw_size, digest, raw_digest = self.disk[key]
        blob = path.read_bytes()
        if len(blob) != size or hashlib.sha256(blob).digest() != digest:
            raise ReplayStorageError(f"Generated block changed for {key[0][0]}")
        raw = CODEC.decompress(blob, raw_size, asbytes=True)
        if hashlib.sha256(raw).digest() != raw_digest:
            raise ReplayStorageError(f"Decoded native block changed for {key[0][0]}")
        result = pickle.loads(raw)  # Only process-generated bytes, verified above.
        self.disk.move_to_end(key)
        self.disk_reads += 1
        self._remember(key, result)
        return result

    def _remember(self, key, block):
        self.resident[key] = block
        while len(self.resident) > BLOCK_LRU:
            self.resident.popitem(last=False)

    def read_slice(self, key, start, stop, template):
        if stop <= start:
            return template.copy(deep=True)
        first, last = start // BLOCK_ROWS, (stop - 1) // BLOCK_ROWS
        needed = range(first, last + 1)
        for i in needed:
            if (key, i) in self.disk:
                self.disk.move_to_end((key, i))
        missing = [i for i in needed if (key, i) not in self.disk and (key, i) not in self.resident]
        if missing:
            view, _, clock, expected = self.records[key]
            frame = self.owner.rebuild(key[0], clock)
            if semantic_digest(frame) != expected:
                raise ReplayStorageError(f"Native reanalysis differed from the original for {key[0]}")
            self.rebuilt += 1
            next_block = last + 1
            prefetch = ((next_block,) if next_block * BLOCK_ROWS < len(view.index)
                        and (key, next_block) not in self.disk and (key, next_block) not in self.resident else ())
            for i in (*missing, *prefetch):
                block = frame.iloc[i * BLOCK_ROWS:(i + 1) * BLOCK_ROWS].copy(deep=True)
                self._store((key, i), block)
                self._remember((key, i), block)
        pieces = []
        for i in needed:
            offset = i * BLOCK_ROWS
            block = self._load((key, i))
            pieces.append(block.iloc[max(0, start - offset):stop - offset])
        return pieces[0].copy(deep=True) if len(pieces) == 1 else pd.concat(pieces).copy(deep=True)


class ReplayStorage(OriginalLifecycle):
    def install(self, root):
        result = AnalyzedBlocks(self, root)
        self.caches.append(result)
        return result

    def audit(self):
        return {**super().audit(), "resident_block_hits": sum(cache.hits for cache in self.caches),
                "block_rows": BLOCK_ROWS, "block_lru": BLOCK_LRU, "maximum_storage_bytes": DISK_LIMIT}
